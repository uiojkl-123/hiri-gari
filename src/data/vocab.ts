/** 전체 단어 개수 */
export const VOCAB_COUNT = VOCAB.length;

/** id로 단어 조회 */
export function getVocabById(id: string): Vocab | undefined {
  return VOCAB.find((v) => v.id === id);
}

/** 레벨·카테고리로 필터링 (null이면 전체) */
export function filterVocab(
  level: StudyLevel | null,
  category: VocabCategory | null
): Vocab[] {
  return VOCAB.filter(
    (v) =>
      (level === null || v.level === level) &&
      (category === null || v.category === category)
  );
}

/** 데이터에 실제로 존재하는 카테고리 목록 (표시 순서 유지) */
export function getUsedCategories(): VocabCategory[] {
  const order = Object.keys(VOCAB_CATEGORY_LABEL) as VocabCategory[];
  const used = new Set(VOCAB.map((v) => v.category));
  return order.filter((c) => used.has(c));
}
